def projections(symbols):
    """Resolve projection storage from ELF symbols, with compatibility defaults."""
    return (symbols.get('SPR_RECORDS', OLD_SPR_RECORDS),
            symbols.get('SPR_ORDER', OLD_SPR_ORDER))


def world(symbols=None):
    """Resolve the logic bank from the supplied ELF or the active memory map."""
    return (symbols.get('LOGICBANK', 0x28) << 16) if symbols is not None else LOGIC_BASE


def fill(text):
    """Expand @MM:NAME@ and @MM:NAME+0xOFF@ address placeholders."""
    import re
    def value(m):
        return '0x%06x' % (NAMES[m.group(1)] + int(m.group(2) or '0', 16))
    return re.sub(r'@MM:([A-Z][A-Z0-9_]*)(\+0x[0-9a-fA-F]+)?@', value, text)


def write_outputs(folder):
    """memmap.inc for the assembler and memmap.scm for the linker maps."""
    from pathlib import Path
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    asm = ['; Generated from tools/memmap.py: do not edit.', '#ifndef MEMMAP_INC', '#define MEMMAP_INC 1']
    scm = [';; Generated from tools/memmap.py: do not edit.']
    fields = {f[0] for f in FIELDS}
    for name, value in NAMES.items():
        scm.append(f'(define {name} #x{value:x})')
        if name not in fields:          # record fields stay with their record includes
            if name in ('WALL_PAGE_COUNT', 'WALL_BITMAP_BYTES', 'GEN_BITMAP_BYTES', 'SAVE_BLOCKS'):
                # Host/native bounds without adding symbols to existing engine ELFs.
                asm.append(f'#define {name} 0x{value:x}')
            else:
                asm.append(f'{name:<28} .equ 0x{value:06x}')
    asm.append('#endif')
    (folder / 'memmap.inc').write_text('\n'.join(asm) + '\n')
