def _define():
    names = {}
    for name, start, size, scoped, _ in REGIONS:
        for key, value in ((name, start), (name + '_SIZE', size), (name + '_END', start + size),
                           (name + '_LAST', start + size - 1)):
            assert key not in names, f'memmap: {key} defined twice'
            names[key] = value
    for name, address, size, _ in REGISTERS:
        assert name not in names, f'memmap: {name} defined twice'
        names[name] = address
    for name, base, offset, _ in FIELDS:
        assert name not in names, f'memmap: {name} defined twice'
        assert base in names, f'memmap: field {name} names no region {base}'
        names[name] = offset
    def put(key, value):
        assert names.get(key, value) == value, f'memmap: {key} defined twice with different values'
        names[key] = value
    for name, address, _ in DIRECT_PAGES:
        if address is not None:
            put(name, address)
    for name, page, offset, size, _ in DP:
        put(name, offset)
    for name, address, size, _ in BANK0:
        for key, value in ((name, address), (name + '_SIZE', size), (name + '_END', address + size)):
            put(key, value)
    for name, address, size, _ in ROM:
        put(name, address)
    for name, address, _ in BANK_OFFSETS:
        put(name, address & 0xffff)
    for name, address, _ in BANK_NUMBERS:
        put(name, address >> 16)
    for alias, name in ALIASES.items():
        assert alias not in names, f'memmap: alias {alias} defined twice'
        names[alias] = names[name]
    for name, value in CONSTANTS.items():
        assert name not in names, f'memmap: {name} defined twice'
        names[name] = value
    return names


