"""Compile source-order campaign metadata for native flow and episode menus."""
import json
import re
from pathlib import Path

END = 65535
ABSENT = 65534


def page_bodies(raw):
    text = raw.decode('latin1').replace('\r', '')
    return [body for part in re.split(r'\^P(?:AGE)?[^\n]*\n', text)[1:]
            if (body := re.sub(r'\n?\^E\s*$', '', part)).strip()]


def metadata(game, ending_counts):
    campaign = game.campaign
    order = campaign.document['episode_menu_order']
    ends, end_at = {}, 0
    for key in order:
        ending = campaign.episodes[key]['ending_id']
        count = ending_counts[ending]
        if not 1 <= count <= 255: raise ValueError('ending page count outside native range')
        ends[ending] = [end_at, count]
        end_at += count
    episodes, floors = [], []
    for ep, key in enumerate(order):
        entry = campaign.episodes[key]
        members = sorted((f for f in campaign.floors.values() if f['episode_id'] == key),
                         key=lambda f:f['display_floor_number'])
        ratios = [f['source_floor_index'] for f in members if f['tally_kind'] == 'par_ratios']
        episodes.append(dict(title=entry['title'], start=entry['start_source_floor_index'],
                             floors=[f['source_floor_index'] for f in members], ratios=len(ratios)))
        for floor in members:
            index = floor['source_floor_index']
            row = dict(index=index, episode=ep, local=floor['display_floor_number'],
                       par=floor.get('par_seconds', 0), bonus=floor.get('bonus_points', 0),
                       ratio_offset=ratios.index(index)*8 if index in ratios else END,
                       ratio_count=len(ratios), ending=ends[entry['ending_id']])
            for name, triggers in [('normal', ('normal_exit',)), ('secret', ('secret_exit',)),
                                   ('victory', ('bj_exit', 'boss_death')), ('spear', ('spear_pickup',))]:
                routes = [campaign.routes[index,t] for t in triggers if (index,t) in campaign.routes]
                if len(routes) > 1: raise ValueError('ambiguous native completion trigger')
                route = routes[0] if routes else None
                row[name] = ABSENT if route is None else (END if route['destination_kind']=='ending'
                    else route['target_source_floor_index'] | (0 if route['show_tally'] else 0x8000)
                    | (0x4000 if route.get('arrival')=='preserve_player_pose' else 0))
            floors.append(row)
    floors.sort(key=lambda f:f['index'])
    result = dict(profile=game.key, episodes=episodes, floors=floors, ending_pages=end_at,
                  native_index_order='source', ratio_bytes=max(e['ratios'] for e in episodes)*8)
    if game.spear:
        result['music_events'] = {name:game.music_names.index(song) for name,song in game.document['audio']['events'].items()}
    return result


def tables(meta):
    def words(name, values):
        lines = ['              .public '+name, name+':']
        for start in range(0, len(values), 10):
            lines.append('              .word '+', '.join(str(v) for v in values[start:start+10]))
        return lines
    floors, episodes = meta['floors'], meta['episodes']
    constants = ['; Generated by build_campaign.py; native indices are source floor indices.',
        'CAMPAIGN_FLOORS .equ '+str(len(floors)), '#define CAMPAIGN_EPISODES '+str(len(episodes)),
        '#define CAMPAIGN_COLD_PAGES 1',
        'CAMPAIGN_RATIO_BYTES .equ '+str(meta['ratio_bytes'])]
    if meta['profile'].startswith('spear'):
        constants += ['#define CAMPAIGN_SPEAR 1']
        constants += ['CAMPAIGN_MUSIC_'+name.upper()+' .equ '+str(sid)
                      for name,sid in meta['music_events'].items()]
    flow_section = 'registereddata'
    flow = [f'              .section {flow_section}, data, root']
    for name,key in [('Normal','normal'),('Secret','secret'),('Victory','victory'),('Spear','spear'),
                     ('Par','par'),('Local','local'),('Episode','episode'),('RatioOffset','ratio_offset'),
                     ('RatioCount','ratio_count')]:
        flow += words('campaign'+name, [f[key] for f in floors])
    for name,index in [('EndBase',0),('EndCount',1)]:
        flow += words('campaign'+name,[f['ending'][index] for f in floors])
    flow += words('campaignBonus',[f['bonus'] & 65535 for f in floors])
    menu_section = 'registeredmenudata'
    menu = [f'              .section {menu_section}, data, root']
    menu += words('campaignEpisodeStart',[e['start'] for e in episodes])
    menu += words('campaignEpisodeLength',[len(e['floors']) for e in episodes])
    menu += ['episodeFloorPointers:', '              .word '+', '.join('.word0 (episodeFloors%d)'%i for i in range(len(episodes)))]
    for i,e in enumerate(episodes): menu += words('episodeFloors%d'%i,e['floors'])
    menu += ['episodeItems:','              .word '+', '.join('.word0 (episodeTitle%d)'%i for i in range(len(episodes))),
             'episodeActive: .byte '+','.join('1' for e in episodes)]
    for i,e in enumerate(episodes):
        menu += ['episodeTitle%d: .asciz '%i+json.dumps(e['title'])]
    return {'campaign.inc':'\n'.join(constants)+'\n', 'campaign-flow.inc':'\n'.join(flow)+'\n',
            'campaign-menu.inc':'\n'.join(menu)+'\n'}


def main():
    from wolfdata import ROOT, PROFILE, source_data
    source = source_data(); chunks = source.graphics()
    counts = {}
    for name,ending in PROFILE.campaign.endings.items():
        chunk = source.graphics_layout['roles'][ending['picture_role']]+ending.get('picture_offset',0)
        counts[name] = 10 if PROFILE.spear else len(page_bodies(chunks[chunk]))
    meta = metadata(PROFILE,counts)
    if meta['ratio_bytes'] > (112 if PROFILE.spear else 64) or any(len(e['floors']) > (21 if PROFILE.spear else 10) for e in meta['episodes']):
        raise SystemExit('campaign exceeds the selected native floor or ratio capacity')
    out = ROOT/'build/gen'; out.mkdir(parents=True,exist_ok=True)
    for name,body in tables(meta).items(): (out/name).write_text(body)
    if PROFILE.spear:
        labels = [f'spearFloor{i+1}' for i in range(PROFILE.floors)]
        body = 'floorItems: .word '+','.join('.word0 ('+label+')' for label in labels)+'\n'
        body += ''.join(label+': .asciz '+json.dumps('Floor '+str(i+1))+'\n' for i,label in enumerate(labels))
        (out/'spear-floor-items.inc').write_text(body)
    (out/'campaign.json').write_text(json.dumps(meta,indent=2)+'\n')
    print('%s: %d episodes, %d floors, %d ending pages' %
          (PROFILE.key,len(meta['episodes']),len(meta['floors']),meta['ending_pages']))


if __name__=='__main__': main()
