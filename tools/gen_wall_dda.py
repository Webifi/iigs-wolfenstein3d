"""Generate exact difference-of-crossing-times wall DDA loops in bank $0D.

Y is major minus minor crossing time (minus one for horizontal major, to
preserve horizontal wins on equality). Control flow retains the borrow bit.
The ray setup record selects a fixed 256-byte slot at $0D:8000-87FF.
Only minor-axis steps and solid hits materialize absolute distances. All
unsigned overflows saturate exactly like the original DDA. Every passed floor
cell receives the current word stamp: the same traversal supplies gameplay
visibility, including actors that moved beyond their old object markers.
"""
import memmap
from pathlib import Path
out = [';;; Generated by tools/gen_wall_dda.py.', '              .section logiccode, text, root', 'wallDDA:      jmp abs:0x8000', '              .extern lightNote', '              .section wallcast, text, root']
def ins(s): out.append('              '+s)
def lab(s): out.append(s+':')
def seq(items):
    for s in items: ins(s)
def move(axis,sign):
    return ['txa','clc',f'adc ##{(sign*128)&65535}','tax'] if axis=='V' else [('inx' if sign>0 else 'dex')]*2
for q,sx,sy in [('PN',1,-1),('PP',1,1),('NN',-1,-1),('NP',-1,1)]:
    for axis in ['V','H']:
        p='wd'+q+axis
        major,minor,dm,dn=('TX','TY','DX','DY') if axis=='V' else ('TY','TX','DY','DX')
        bias=axis=='H'; add='sec' if bias else 'clc'
        lab(p)
        seq([f'lda dp:{major}','clc' if bias else 'sec',f'sbc dp:{minor}','tay',f'bcs {p}Minor'])
        lab(p+'Major')
        seq(move(axis,sx if axis=='V' else sy)+[memmap.fill('lda long:@MM:TILE_MIRROR@,x'),f'bne {p}MajorTile'])
        lab(p+'MajorNext')
        seq(['lda dp:VISSTAMP',memmap.fill('sta long:@MM:VIS_STAMPS@,x')])
        seq(['tya','clc',f'adc dp:{dm}','tay',f'bcc {p}Major',add,f'adc dp:{minor}',f'bcc {p}Minor',
             'lda ##65535','sec',f'sbc dp:{minor}']+(['dec a'] if bias else [])+['tay',f'bra {p}Minor'])
        lab(p+'MajorTile')
        seq([f'bpl {p}MajorHit'])
        lab(p+'MajorNeg')
        seq([f'bra {p}MajorNext'])
        lab(p+'MajorHit')
        seq(['sta dp:TILE','tya',add,f'adc dp:{minor}','sta dp:DIST','clc',f'adc dp:{dm}',f'bcc {p}MajorReady','lda ##65535'])
        lab(p+'MajorReady')
        seq([f'sta dp:{major}']+(['lda ##1','sta dp:SIDE'] if bias else ['stz dp:SIDE'])+['lda dp:VISSTAMP',memmap.fill('sta long:@MM:VIS_STAMPS@,x'),'jmp long:solidTile'])
        lab(p+'Minor')
        seq(move('H' if axis=='V' else 'V',sy if axis=='V' else sx)+[memmap.fill('lda long:@MM:TILE_MIRROR@,x'),f'bne {p}MinorTile'])
        lab(p+'MinorNext')
        seq(['lda dp:VISSTAMP',memmap.fill('sta long:@MM:VIS_STAMPS@,x')])
        seq([f'lda dp:{minor}','clc',f'adc dp:{dn}',f'bcs {p}MinorSaturate',f'sta dp:{minor}',
             'tya','sec',f'sbc dp:{dn}','tay',f'bcs {p}Minor',f'jmp abs:.word0 ({p}Major)'])
        lab(p+'MinorSaturate')
        seq(['tya','clc',f'adc dp:{minor}','inc a','tay','lda ##65535',f'sta dp:{minor}']+
            (['tya',f'beq {p}Minor'] if not bias else [])+[f'jmp abs:.word0 ({p}Major)'])
        lab(p+'MinorTile')
        seq([f'bpl {p}MinorHit'])
        lab(p+'MinorNeg')
        seq([f'bra {p}MinorNext'])
        lab(p+'MinorHit')
        seq(['sta dp:TILE','tya',add,f'adc dp:{minor}',f'sta dp:{major}',f'lda dp:{minor}','sta dp:DIST','clc',f'adc dp:{dn}',f'bcc {p}MinorReady','lda ##65535'])
        lab(p+'MinorReady')
        seq([f'sta dp:{minor}']+(['stz dp:SIDE'] if bias else ['lda ##1','sta dp:SIDE'])+['lda dp:VISSTAMP',memmap.fill('sta long:@MM:VIS_STAMPS@,x'),'jmp long:solidTile'])
        # Exact 0x8000 (other statics, open doors) jumps onward. Only a light
        # sentinel calls lightNote. The trampoline uses the slot's padding,
        # so the negative bra still reaches it.
        lab(p+'MajorTramp')
        seq(['cmp ##0x8000', f'bne {p}MajorCall', f'jmp abs:.word0 ({p}MajorNext)'])
        lab(p+'MajorCall')
        seq(['jsr abs:.word0 (lightNote)', f'jmp abs:.word0 ({p}MajorNext)'])
        lab(p+'MinorTramp')
        seq(['cmp ##0x8000', f'bne {p}MinorCall', f'jmp abs:.word0 ({p}MinorNext)'])
        lab(p+'MinorCall')
        seq(['jsr abs:.word0 (lightNote)', f'jmp abs:.word0 ({p}MinorNext)'])
        lab(p+'End')
        ins(f'.space 256-({p}End-{p})')
# neg, direct target, trampoline. setView points neg at the trampoline only
# while the view is below full width. Full view keeps the direct branch.
out += ['              .section logictail, text, root', '              .public ddaNegTable', 'ddaNegTable:']
for q, sx, sy in [('PN', 1, -1), ('PP', 1, 1), ('NN', -1, -1), ('NP', -1, 1)]:
    for axis in ['V', 'H']:
        p = 'wd' + q + axis
        for kind in ['Major', 'Minor']:
            out.append(f'              .word .word0 {p}{kind}Neg, .word0 {p}{kind}Next, .word0 {p}{kind}Tramp')
out.append('              .word 0')
Path(__file__).resolve().parents[1].joinpath('src/iigs/wall_dda.inc').write_text('\n'.join(out)+'\n')
