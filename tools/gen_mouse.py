"""Mouse gains in Q8 control units per count, with sixteen sensitivity steps.

Turning uses 7,200 control units per revolution. Movement follows the same
sensitivity curve with a cap at base gain 82; step 4 produces a Q8 movement
gain of 320.
Nibble product tables let the input consumer multiply without a general
multiplication routine.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOOM_TURN = (27, 30, 33, 37, 41, 45, 50, 55, 61, 68, 75, 84, 93, 103, 114, 126)
TURN = tuple(round(n * 7200 / 256) for n in DOOM_TURN)
MOVE = tuple(round(min(n, 82) * 320 / 41) for n in DOOM_TURN)

def generate():
    lines = [';;; Generated by tools/gen_mouse.py; Q8 products for each nibble.']
    for label, gains in [('mouseTurnProducts', TURN), ('mouseMoveProducts', MOVE)]:
        lines.append(label + ':')
        lines.extend(' .word ' + ','.join(str(gain * n) for n in range(16)) for gain in gains)
    (ROOT / 'build/gen/mouse.inc').write_text('\n'.join(lines) + '\n')

if __name__ == '__main__':
    generate()
