"""Loading lettering in fixed aligned slots; no palette lookup or replacement."""
from pathlib import Path

ADVANCE = 51
LEFT = 134
TOP = 86
# Keep the small Black Ops One face and its one-pixel contour. The bright
# strokes use slot 1; slots 13 and 14 soften steps inside that contour.
# A dot leaves the background untouched. Zero is the black outline.
ROWS = (
    '000....00EE00..00E00...000000.00EE000000000.0000E00',
    '010...0D1111D0.0111D0..01D11D0011110011D1100D1D1110',
    'E1E...011DD110.0D1110..E1ED1100D11D0E11D11E011ED110',
    'E1E...E11EE11E.01111D0.E1EE11E.E11E.E11111EE11EEDD0',
    'E1E000E11EE11E.E11D110.E1EE11E.E11E.E1D111EE11D1110',
    'E1ED10011DD1100D1D111D0E1ED1100D11D0E1D111E011DD11E',
    '01D1100D1111D00111D111001D11D001111001ED1100D111110',
    '000000.00EE00.00E000E00000000.00EE000000000.00EEE00',
)


def pixels(left=LEFT, top=TOP):
    return [(left+x, top+y, int(c, 16))
            for y, row in enumerate(ROWS) for x, c in enumerate(row) if c != '.']


def block():
    """The existing DrawWordBlock alpha format, on an even SHR pixel."""
    from frontend.native_assets import alpha
    return alpha([[None if c == '.' else int(c, 16) for c in row] for row in ROWS])


def assembly():
    data = block()
    lines = [';;; Generated by tools/loading_glyphs.py; fixed aligned ink slots.',
             f'LOADING_ADVANCE .equ {ADVANCE}', 'loadingWord:']
    lines += ['              .byte ' + ','.join(f'0x{v:02x}' for v in data[i:i+16])
              for i in range(0, len(data), 16)]
    return '\n'.join(lines) + '\n'


def text_rows(text):
    """Use the approved small face and its one-pixel, four-slot contour."""
    import json
    root=Path(__file__).resolve().parents[1]
    glyphs=json.loads((root/'data/frontend-fonts/BlackOpsOne-Regular.ttf.6.json').read_text())['glyphs']
    top=min(y for c in 'ABCDEFGHIJKLMNOPQRSTUVWXYZ' for y,row in enumerate(glyphs[c]) if '#' in row)
    face=set();advance=0
    for c in text:
        if c==' ':advance+=5;continue
        face.update((advance+1+x,y+1) for y,row in enumerate(glyphs[c][top:top+8]) for x,v in enumerate(row) if v=='#')
        advance+=len(glyphs[c][0])+2
    outline={(x+dx,y+dy) for x,y in face for dx in (-1,0,1) for dy in (-1,0,1)}
    rows=[]
    for y in range(8):
        row=[]
        for x in range(advance):
            near=sum((x+dx,y+dy) in face for dx,dy in ((1,0),(-1,0),(0,1),(0,-1)))
            diagonal=sum((x+dx,y+dy) in face for dx in (-1,1) for dy in (-1,1))
            ink=1 if (x,y) in face else 13 if near>=2 else 14 if near and diagonal>=2 else 0 if (x,y) in outline else None
            row.append(ink)
        rows.append(row)
    return rows,advance


def busy_assembly():
    """Static words and one digit share the native masked-word compositor."""
    from frontend.native_assets import alpha
    approved,width=text_rows('LOADING')
    assert width==ADVANCE and tuple(''.join('.' if v is None else format(v,'X') for v in row) for row in approved)==ROWS
    lines=[';;; Generated by tools/loading_glyphs.py; centered at an even U_X.',
           '#if defined(BUSY_PREFIX_DATA)',
           '              .extern loadingWord, busySaving, busyHigh',
           '              .extern '+', '.join(f'busyDigit{n}' for n in range(1,10))]
    def emit(name,rows):
        data=alpha(rows);lines.extend(['              .public '+name,name+':'])
        lines.extend('              .byte '+','.join(f'0x{v:02x}' for v in data[i:i+16]) for i in range(0,len(data),16))
    saving,sw=text_rows('SAVING');high,hw=text_rows('NEW HIGH SCORE');prefix,pw=text_rows('INSERT DISK ')
    assert pw%2==0
    emit('busyPrefix0',prefix);emit('busyPrefix1',[[None]+row for row in prefix])
    def words(name,values):lines.extend(['              .public '+name,name+':','              .word '+', '.join(map(str,values))])
    words('busyWordPtrs',['.word0 (loadingWord)','.word0 (busySaving)',0,'.word0 (busyHigh)'])
    words('busyWordWidths',[ADVANCE,sw,0,hw]);words('busyWordLengths',[8,7,14,15])
    words('busyWordOffsets',[-((w//2+2)//2) for w in (ADVANCE,sw,0,hw)])
    digits=[text_rows(str(n)) for n in range(1,10)]
    starts=[-( (pw+w)//2+1) for rows,w in digits]
    words('busyDigitWidths',[pw+w for rows,w in digits])
    words('busyDigitOffsets',[x//2 for x in starts])
    words('busyPrefixPtrs',[f'.word0 (busyPrefix{x&1})' for x in starts])
    words('busyDigitPtrs',[f'.word0 (busyDigit{n})' for n in range(1,10)])
    lines.extend(['#elif defined(BUSY_WORDS_DATA)',
                  '              .public loadingWord',
                  '#include "loading_sign.inc"'])
    emit('busySaving',saving)
    emit('busyHigh',[[None]+row for row in high])
    for n,((rows,w),start) in enumerate(zip(digits,starts),1):emit(f'busyDigit{n}',[[None]*(start&1)+row for row in rows])
    lines.extend(['#else',f'BUSY_PREFIX_BYTES .equ {pw//2}',
                  '              .extern loadingWord, busyPrefix0, busyDigit1',
                  '              .extern busyWordPtrs, busyWordWidths, busyWordLengths, busyWordOffsets',
                  '              .extern busyDigitPtrs, busyDigitWidths, busyDigitOffsets, busyPrefixPtrs',
                  '#endif'])
    return '\n'.join(lines)+'\n'


if __name__ == '__main__':
    root=Path(__file__).resolve().parents[1]
    (root/'src/iigs/loading_sign.inc').write_text(assembly())
    (root/'src/iigs/busy_signs.inc').write_text(busy_assembly())
